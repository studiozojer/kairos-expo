import React from 'react';
import TestRenderer, { act } from 'react-test-renderer';
import { TextInput } from 'react-native';
import AsyncStorage from '@react-native-async-storage/async-storage';
import { getAllStarPositions } from '../../../../../modules/kairos';
import { StarLibraryPanel } from '../StarLibraryPanel';
let mockAccount: {ready:boolean;account:{did:string}|null}={ready:true,account:null};
jest.mock('@/auth/auth-context',()=>({useOptionalAuth:()=>mockAccount}));
jest.mock('../../../../../modules/kairos',()=>({getAllStarPositions:jest.fn()}));
const native=jest.mocked(getAllStarPositions);
const catalog=[{name:'Arcturus',designation:'alBoo',display_designation:'α Boo',constellation:'Bootes',magnitude:-.05,longitude:204.2,sign:'Libra',degrees:24,minutes:12},{name:'Regulus',designation:'alLeo',display_designation:'α Leo',constellation:'Leo',magnitude:1.36,longitude:150,sign:'Virgo',degrees:0,minutes:0}];
test('real personal-library owner persists UI edits, survives remount and isolates accounts without reloading catalog',async()=>{
  await AsyncStorage.clear(); native.mockResolvedValue(JSON.stringify(catalog));
  let view!:TestRenderer.ReactTestRenderer;
  await act(async()=>{view=TestRenderer.create(<StarLibraryPanel/>);});
  const press=(label:string)=>view.root.findAll(node=>typeof node.props.onPress==='function').find(node=>node.props.accessibilityLabel===label)!;
  await act(async()=>press('Add Arcturus').props.onPress());
  expect(press('Remove Arcturus')).toBeDefined();
  expect(JSON.parse((await AsyncStorage.getItem('kairos.star-library.v1:anonymous'))!).stars).toEqual([{id:'star:arcturus',name:'Arcturus'}]);
  act(()=>view.root.findByType(TextInput).props.onChangeText('α Leo'));
  expect(press('Add Regulus')).toBeDefined();
  expect(view.root.findAll(node=>typeof node.props.onPress==='function').some(node=>node.props.accessibilityLabel==='Add Arcturus')).toBe(false);
  act(()=>view.unmount()); await act(async()=>{view=TestRenderer.create(<StarLibraryPanel/>);});
  expect(press('Remove Arcturus')).toBeDefined();
  mockAccount={ready:true,account:{did:'did:plc:other'}};
  await act(async()=>view.update(<StarLibraryPanel/>));
  expect(view.root.findAll(node=>typeof node.props.onPress==='function').some(node=>node.props.accessibilityLabel==='Remove Arcturus')).toBe(false);
  expect(press('Add Arcturus')).toBeDefined();
  await act(async()=>press('Add Regulus').props.onPress());
  expect(JSON.parse((await AsyncStorage.getItem('kairos.star-library.v1:did:plc:other'))!).stars).toEqual([{id:'star:regulus',name:'Regulus'}]);
  expect(JSON.parse((await AsyncStorage.getItem('kairos.star-library.v1:anonymous'))!).stars[0].name).toBe('Arcturus');
  expect(native).toHaveBeenCalledTimes(1);
  expect(JSON.parse(native.mock.calls[0][0])).toEqual({datetime:'2000-01-01T12:00:00.000Z',zodiac_system:'Tropical'});
  act(()=>view.unmount());
});
test('inspection does not change membership; detail return preserves populated search and independent removal', async () => {
  mockAccount = { ready: true, account: { did: 'did:plc:ux' } };
  let view!: TestRenderer.ReactTestRenderer;
  await act(async () => { view = TestRenderer.create(<StarLibraryPanel />); });
  const press = (label: string) => view.root.findAll(node => typeof node.props.onPress === 'function').find(node => node.props.accessibilityLabel === label)!;
  act(() => view.root.findByType(TextInput).props.onChangeText('Arcturus'));
  act(() => press('Details for Arcturus').props.onPress());
  expect(await AsyncStorage.getItem('kairos.star-library.v1:did:plc:ux')).toBeNull();
  await act(async () => press('Add to my stars').props.onPress());
  expect(JSON.parse((await AsyncStorage.getItem('kairos.star-library.v1:did:plc:ux'))!).stars).toHaveLength(1);
  act(() => press('Back').props.onPress());
  expect(view.root.findByType(TextInput).props.value).toBe('Arcturus');
  act(() => press('Inspect Arcturus').props.onPress());
  expect(press('Remove from my stars')).toBeDefined();
  act(() => press('Back').props.onPress());
  await act(async () => press('Remove Arcturus').props.onPress());
  expect(JSON.parse((await AsyncStorage.getItem('kairos.star-library.v1:did:plc:ux'))!).stars).toEqual([]);
  act(() => press('Clear star search').props.onPress());
  expect(view.root.findByType(TextInput).props.value).toBe('');
  expect(press('Add Regulus')).toBeDefined();
  act(() => view.unmount());
});
